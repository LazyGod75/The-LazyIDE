/// Fan-in dependency merge, success case: a step with two upstream
/// branches must see BOTH branches' files in its worktree — never just
/// the base_branch's, silently dropping the other dependency.
#[test]
fn agent_create_worktree_merges_extra_branch_into_worktree() {
    use super::agent_create_worktree_inner;

    let repo_dir = TempDir::new().expect("TempDir");
    let repo_path = setup_git_repo(&repo_dir);

    // Dependency A: a branch off HEAD adding A.md.
    let branch_a = "agent/dep-a".to_string();
    quiet_command(git_binary()).args(["checkout", "-b", &branch_a]).current_dir(&repo_path).output().expect("checkout dep-a");
    std::fs::write(std::path::Path::new(&repo_path).join("A.md"), "# A\n").expect("write A.md");
    quiet_command(git_binary()).args(["add", "A.md"]).current_dir(&repo_path).output().expect("add A.md");
    quiet_command(git_binary()).args(["commit", "-m", "dep-a"]).current_dir(&repo_path).output().expect("commit dep-a");

    // Dependency B: a SIBLING branch off the same HEAD adding B.md
    // (independent file, no conflict with A.md).
    quiet_command(git_binary()).args(["checkout", "-"]).current_dir(&repo_path).output().expect("back to main");
    let branch_b = "agent/dep-b".to_string();
    quiet_command(git_binary()).args(["checkout", "-b", &branch_b]).current_dir(&repo_path).output().expect("checkout dep-b");
    std::fs::write(std::path::Path::new(&repo_path).join("B.md"), "# B\n").expect("write B.md");
    quiet_command(git_binary()).args(["add", "B.md"]).current_dir(&repo_path).output().expect("add B.md");
    quiet_command(git_binary()).args(["commit", "-m", "dep-b"]).current_dir(&repo_path).output().expect("commit dep-b");

    quiet_command(git_binary()).args(["checkout", "main"]).current_dir(&repo_path).output().expect("back to main");

    let branch = "agent/M-join-a-b".to_string();
    let merge_branches = vec![branch_b.clone()];
    let wt_path = agent_create_worktree_inner(&repo_path, &branch, Some(&branch_a), Some(&merge_branches))
        .expect("agent_create_worktree_inner with a valid merge_branches entry must succeed");

    assert!(
        std::path::Path::new(&wt_path).join("A.md").exists(),
        "worktree must contain base_branch's A.md"
    );
    assert!(
        std::path::Path::new(&wt_path).join("B.md").exists(),
        "worktree must contain the MERGED dependency's B.md — a fan-in dependency must never be silently dropped"
    );
}

