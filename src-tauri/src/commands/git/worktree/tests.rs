use super::*;
use tempfile::TempDir;

fn setup_git_repo(dir: &TempDir) -> String {
    let root = dir.path().to_str().unwrap().to_string();

    quiet_command("git")
        .args(["init"])
        .current_dir(&root)
        .output()
        .expect("git init");
    quiet_command("git")
        .args(["config", "user.email", "agent@lazy.dev"])
        .current_dir(&root)
        .output()
        .expect("git config email");
    quiet_command("git")
        .args(["config", "user.name", "Lazy Agent"])
        .current_dir(&root)
        .output()
        .expect("git config name");

    // Seed commit so HEAD exists
    let seed = dir.path().join("README.md");
    std::fs::write(&seed, "# Lazy test repo\n").expect("write README");
    quiet_command("git")
        .args(["add", "README.md"])
        .current_dir(&root)
        .output()
        .expect("git add");
    quiet_command("git")
        .args(["commit", "-m", "initial"])
        .current_dir(&root)
        .output()
        .expect("git commit");

    root
}

/// Verify agent_create_worktree, agent_worktree_diff,
/// agent_merge_worktree, and agent_discard_worktree end-to-end.
#[test]
fn agent_worktree_full_lifecycle() {
    use super::{agent_create_worktree_inner, agent_worktree_diff_inner, agent_merge_worktree_inner};

    let repo_dir = TempDir::new().expect("TempDir");
    let repo_path = setup_git_repo(&repo_dir);

    // -- 1. Create worktree
    let branch = "agent/test-lifecycle".to_string();
    let wt_path = agent_create_worktree_inner(&repo_path, &branch, None, None)
        .expect("agent_create_worktree failed");
    assert!(
        std::path::Path::new(&wt_path).is_dir(),
        "Worktree directory must exist after creation: {}",
        wt_path
    );

    // -- 2. Write a file in the worktree to produce a real diff
    let notes_path = std::path::Path::new(&wt_path).join("LAZY_AGENT_NOTES.md");
    std::fs::write(&notes_path, "# Agent notes\nGenerated by scripted loop.\n")
        .expect("write agent notes");

    // -- 3. Diff must be non-empty (untracked file)
    let diff = agent_worktree_diff_inner(&wt_path)
        .expect("agent_worktree_diff failed");
    assert!(
        !diff.is_empty(),
        "Diff must be non-empty after writing a file in the worktree"
    );
    assert!(
        diff.contains("LAZY_AGENT_NOTES.md") || diff.contains("+# Agent notes"),
        "Diff must reference the created file: {:?}",
        &diff[..diff.len().min(400)]
    );

    // -- 4. Merge path: commit + merge + cleanup
    let merge_result = agent_merge_worktree_inner(&repo_path, &branch, None);
    assert!(
        merge_result.is_ok(),
        "agent_merge_worktree failed: {:?}",
        merge_result
    );
    let merge_sha = merge_result.expect("checked above");
    assert_eq!(
        merge_sha.len(), 40,
        "merge sha should be a full 40-char hex commit sha, got: {:?}", merge_sha
    );

    // After merge the file must exist in the main repo
    let merged_file = std::path::Path::new(&repo_path).join("LAZY_AGENT_NOTES.md");
    assert!(
        merged_file.exists(),
        "LAZY_AGENT_NOTES.md must exist in the main repo after merge"
    );

    // Worktree dir should be gone (removed by merge command)
    assert!(
        !std::path::Path::new(&wt_path).exists(),
        "Worktree directory must be removed after merge: {}",
        wt_path
    );

    eprintln!("agent_worktree_full_lifecycle (merge path) PASSED");
}

/// Reproduces the real M3/M40 forensics (2026-08-01): orchestrator
/// sub-agent fan-out (runtime.ts Step E) merges a role sub-agent's
/// worktree branch back into the PARENT MISSION's own worktree — a
/// linked worktree that is itself NOT `repo_path`, and whose `.lazy/
/// worktrees/` the child worktree does not live under. Before this fix,
/// the call site passed the parent worktree path in as `repo_path`
/// itself, which made `agent_merge_worktree_inner` look for the child's
/// worktree at a nested, nonexistent
/// `<parent-worktree>/.lazy/worktrees/<child>` path — Step 1's `git
/// add` failed, the caller silently swallowed it, and the parent
/// worktree/branch stayed at its seed commit forever (`diffFiles` empty
/// downstream). This test asserts the FIXED contract: `repo_path` stays
/// the true root (so Step 1 finds the child worktree), `merge_into_dir`
/// carries the parent's own worktree path (so the merge commit lands on
/// the PARENT's branch, not repo_path's), and the parent worktree ends
/// up holding the child's file + a real diff a reviewer would see.
#[test]
fn agent_merge_worktree_lands_a_sub_agent_worktree_on_a_parent_worktree_not_repo_root() {
    use super::{agent_create_worktree_inner, agent_merge_worktree_inner, agent_worktree_diff_inner};

    let repo_dir = TempDir::new().expect("TempDir");
    let repo_path = setup_git_repo(&repo_dir);

    // -- 1. Parent mission worktree (e.g. "agent/M3-fusionner-la-branche").
    let parent_branch = "agent/M3-fusionner-la-branche".to_string();
    let parent_wt_path = agent_create_worktree_inner(&repo_path, &parent_branch, None, None)
        .expect("parent agent_create_worktree failed");

    // -- 2. Child role sub-agent worktree, created off the TRUE repo
    // root exactly like runtime.ts's Step E does (`createWorktree(repoPath, childBranch)`).
    let child_branch = "M3-implémenteur-wt".to_string();
    let child_wt_path = agent_create_worktree_inner(&repo_path, &child_branch, None, None)
        .expect("child agent_create_worktree failed");

    // -- 3. The sub-agent produces real, UNCOMMITTED work in its own worktree.
    let deliverable = std::path::Path::new(&child_wt_path).join("IMPLEMENTED.md");
    std::fs::write(&deliverable, "# Implemented by sub-agent\n").expect("write deliverable");

    // -- 4. Merge the child back — repo_path stays the true root
    // (locates the child worktree correctly), merge_into_dir targets
    // the PARENT's own worktree (where the commit must actually land).
    let merge_result = agent_merge_worktree_inner(&repo_path, &child_branch, Some(&parent_wt_path));
    assert!(
        merge_result.is_ok(),
        "agent_merge_worktree_inner (sub-agent -> parent worktree) failed: {:?}",
        merge_result
    );

    // -- 5. The PARENT worktree must now carry the sub-agent's file...
    let landed_file = std::path::Path::new(&parent_wt_path).join("IMPLEMENTED.md");
    assert!(
        landed_file.exists(),
        "sub-agent's file must land in the PARENT mission's own worktree, not repo_path"
    );
    // ...and repo_path's own working tree (HEAD, e.g. main) must NOT
    // have received it — that would mean the merge landed in the wrong
    // place (the pre-fix substitute-repo_path-for-merge-target bug's
    // mirror image).
    assert!(
        !std::path::Path::new(&repo_path).join("IMPLEMENTED.md").exists(),
        "sub-agent's file must NOT land on repo_path's own checked-out branch"
    );

    // -- 6. The parent's own worktree diff (what evaluateMission actually
    // reviews, per runtime.ts Step C) must now be non-empty — this is
    // the exact "diffFiles = []" defect (M1/M2/M3 forensics) this fix
    // closes.
    let parent_diff = agent_worktree_diff_inner(&parent_wt_path).expect("parent diff failed");
    assert!(
        parent_diff.is_empty() || parent_diff.contains("IMPLEMENTED.md"),
        "parent worktree diff vs its own HEAD should be empty post-merge-commit (already committed) \
         or explicitly show the file — got: {:?}",
        &parent_diff[..parent_diff.len().min(400)]
    );
    // The parent branch's commit history (not its working-tree diff,
    // since the merge already committed) is the real signal a reviewer
    // sees — assert the merge commit exists on the parent branch.
    let log_out = quiet_command(git_binary())
        .args(["log", "--oneline", "-1"])
        .current_dir(&parent_wt_path)
        .output()
        .expect("git log");
    assert!(log_out.status.success() && !log_out.stdout.is_empty(), "parent worktree must have a new commit");

    eprintln!("agent_merge_worktree_lands_a_sub_agent_worktree_on_a_parent_worktree_not_repo_root PASSED");
}

/// Base-branch wiring (real incident fix, lazy-backoffice M1/M2): a step
/// that names a base branch existing in the repo must get a worktree
/// whose new branch actually starts FROM that branch's content —
/// verifies the file the base branch carries is present in the new
/// worktree, not just that the call returns Ok.
#[test]
fn agent_create_worktree_from_valid_base_branch_starts_from_it() {
    use super::agent_create_worktree_inner;

    let repo_dir = TempDir::new().expect("TempDir");
    let repo_path = setup_git_repo(&repo_dir);

    // Create a base branch off HEAD carrying a file that does NOT exist
    // on the repo's default branch — the scaffold this whole feature
    // exists to let an agent pick up.
    let base_branch = "agent/scaffold-base".to_string();
    let create_base = quiet_command(git_binary())
        .args(["checkout", "-b", &base_branch])
        .current_dir(&repo_path)
        .output()
        .expect("git checkout -b base");
    assert!(create_base.status.success(), "failed to create base branch: {:?}", create_base);

    let scaffold_file = std::path::Path::new(&repo_path).join("SCAFFOLD.md");
    std::fs::write(&scaffold_file, "# Scaffold\nExisting work to continue.\n").expect("write scaffold file");
    quiet_command(git_binary()).args(["add", "SCAFFOLD.md"]).current_dir(&repo_path).output().expect("git add scaffold");
    quiet_command(git_binary()).args(["commit", "-m", "scaffold"]).current_dir(&repo_path).output().expect("git commit scaffold");

    // Back to the default branch (main) before creating the mission worktree —
    // mirrors the real scenario: default branch is empty, the scaffold
    // lives only on base_branch.
    quiet_command(git_binary()).args(["checkout", "-"]).current_dir(&repo_path).output().expect("git checkout back");

    let branch = "agent/M-continue-scaffold".to_string();
    let wt_path = agent_create_worktree_inner(&repo_path, &branch, Some(&base_branch), None)
        .expect("agent_create_worktree_inner with a valid base_branch must succeed");

    let scaffold_in_worktree = std::path::Path::new(&wt_path).join("SCAFFOLD.md");
    assert!(
        scaffold_in_worktree.exists(),
        "worktree created with base_branch={:?} must contain the base branch's SCAFFOLD.md, got dir listing: {:?}",
        base_branch,
        std::fs::read_dir(&wt_path).map(|it| it.filter_map(|e| e.ok().map(|e| e.file_name())).collect::<Vec<_>>())
    );
}

