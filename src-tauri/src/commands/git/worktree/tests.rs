/// for the full root-cause). `merge_into_dir` is exactly what
/// runtime.ts's `mergeWorktree` (src/lib/agents/runtime.ts) passes
/// straight through to the `agent_merge_worktree` Tauri invoke with NO
/// normalization — unlike `repoPath`, which QA B11 already normalizes on
/// the TypeScript side (paths.ts's normalizeRepoPathForGit). A verbatim
/// (`\\?\`-prefixed) `merge_into_dir` carrying even one stray '/' (mixed
/// separators — the orchestrator fan-out's parent worktree path, joined
/// upstream with a hardcoded '/' somewhere in the call chain) used to
/// fail `Command::current_dir` outright with "os error 267"
/// (ERROR_DIRECTORY_NAME_INVALID) before agent_merge_worktree_inner
/// started routing every git subprocess's `current_dir` through
/// `normalize_for_git`. This is the exact "some merges fail, others
/// pass" shape reported in prod: a plain top-level merge
